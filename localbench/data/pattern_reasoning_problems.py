"""Synthetic ARC-AGI-style grid-transformation puzzles: a handful of small
grids demonstrate a single consistent rule, and the model must infer that
rule and apply it to a new grid. Grids/rules are generated by us, so the
correct output is always known exactly -- no hand-labeled dataset needed.
"""

from __future__ import annotations

import random

_RULES = ["flip_horizontal", "flip_vertical", "rotate_90", "transpose", "increment_colors"]


def _make_grid(rng: random.Random, size: int, palette: int) -> list[list[int]]:
    return [[rng.randrange(palette) for _ in range(size)] for _ in range(size)]


def _apply_rule(grid: list[list[int]], rule: str, palette: int) -> list[list[int]]:
    if rule == "flip_horizontal":
        return [row[::-1] for row in grid]
    if rule == "flip_vertical":
        return [row[:] for row in reversed(grid)]
    if rule == "rotate_90":
        return [list(row) for row in zip(*grid[::-1])]
    if rule == "transpose":
        return [list(row) for row in zip(*grid)]
    if rule == "increment_colors":
        return [[(v + 1) % palette for v in row] for row in grid]
    raise ValueError(f"unknown rule: {rule}")


def generate_problems(
    num_problems: int,
    seed: int = 42,
    size: int = 3,
    palette: int = 4,
    num_examples: int = 2,
) -> list[dict]:
    rng = random.Random(seed)
    problems = []
    for i in range(num_problems):
        rule = _RULES[i % len(_RULES)]
        examples = []
        for _ in range(num_examples):
            inp = _make_grid(rng, size, palette)
            out = _apply_rule(inp, rule, palette)
            examples.append({"input": inp, "output": out})
        test_input = _make_grid(rng, size, palette)
        expected_output = _apply_rule(test_input, rule, palette)
        problems.append(
            {
                "id": f"{rule}_{i}",
                "rule": rule,
                "examples": examples,
                "test_input": test_input,
                "expected_output": expected_output,
            }
        )
    return problems
